import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Plugin } from 'vite';
import { defineConfig } from 'vitest/config';
import react from '@vitejs/plugin-react';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoCharacterDir = path.resolve(__dirname, '../Character');

interface RepoCharacterManifest {
  male: string[];
  female: string[];
}

function scanRepoCharacters(): RepoCharacterManifest {
  const listSlot = (subDir: string): string[] => {
    const target = path.join(repoCharacterDir, subDir);
    if (!fs.existsSync(target)) return [];
    return fs
      .readdirSync(target, { withFileTypes: true })
      .filter(
        (ent) =>
          ent.isFile() &&
          !ent.name.startsWith('.') &&
          ent.name.trim() !== '. gitkeep',
      )
      .map((ent) => `${subDir}/${ent.name}`)
      .sort();
  };

  return {
    male: listSlot('Male'),
    female: listSlot('Female'),
  };
}

function contentTypeForFile(filePath: string): string {
  const ext = path.extname(filePath).toLowerCase();
  switch (ext) {
    case '.gltf':
      return 'model/gltf+json; charset=utf-8';
    case '.bin':
      return 'application/octet-stream';
    case '.png':
      return 'image/png';
    case '.jpg':
    case '.jpeg':
      return 'image/jpeg';
    case '.webp':
      return 'image/webp';
    case '.txt':
      return 'text/plain; charset=utf-8';
    default:
      return 'application/octet-stream';
  }
}

/**
 * Exposes read-only repository character bundles (../Character/Male & ../Character/Female)
 * under ./repo-characters/ during dev and static GitHub Pages builds without duplicating binaries in Git.
 */
function repoCharactersPlugin(): Plugin {
  return {
    name: 'repo-characters-static-bridge',
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        if (!req.url) return next();
        const cleanUrl = req.url.split('?')[0];
        const prefix = '/repo-characters/';
        if (!cleanUrl.startsWith(prefix)) return next();

        const subPath = decodeURIComponent(cleanUrl.slice(prefix.length));
        if (subPath === 'manifest.json') {
          const manifest = scanRepoCharacters();
          res.setHeader('Content-Type', 'application/json; charset=utf-8');
          res.end(JSON.stringify(manifest, null, 2));
          return;
        }

        const resolved = path.resolve(repoCharacterDir, subPath);
        if (
          !resolved.startsWith(repoCharacterDir + path.sep) ||
          !fs.existsSync(resolved) ||
          !fs.statSync(resolved).isFile()
        ) {
          res.statusCode = 404;
          res.end('Not found');
          return;
        }

        res.setHeader('Content-Type', contentTypeForFile(resolved));
        fs.createReadStream(resolved).pipe(res);
      });
    },
    writeBundle(outputOptions) {
      const outDir = outputOptions.dir
        ? path.resolve(__dirname, outputOptions.dir)
        : path.resolve(__dirname, 'dist');
      const destRoot = path.join(outDir, 'repo-characters');
      fs.mkdirSync(destRoot, { recursive: true });

      const manifest = scanRepoCharacters();
      fs.writeFileSync(
        path.join(destRoot, 'manifest.json'),
        `${JSON.stringify(manifest, null, 2)}\n`,
        'utf-8',
      );

      for (const relFile of [...manifest.male, ...manifest.female]) {
        const src = path.join(repoCharacterDir, relFile);
        const dst = path.join(destRoot, relFile);
        if (fs.existsSync(src)) {
          fs.mkdirSync(path.dirname(dst), { recursive: true });
          fs.copyFileSync(src, dst);
        }
      }
    },
  };
}

/**
 * Exposes the read-only repository animation library (../animations/*.fbx) under
 * ./repo-animations/ in dev and in production builds, mirroring the character
 * bridge. Discovery is directory-driven: the manifest is generated by walking the
 * directory, so adding or removing an FBX needs no code change.
 */
function repoAnimationsPlugin(): Plugin {
  const animationDir = path.resolve(__dirname, '../animations');

  const scanAnimations = () => {
    if (!fs.existsSync(animationDir)) return [] as string[];
    return fs
      .readdirSync(animationDir, { withFileTypes: true })
      .filter((ent) => ent.isFile() && ent.name.toLowerCase().endsWith('.fbx'))
      .map((ent) => ent.name)
      .sort((a, b) => a.localeCompare(b));
  };

  return {
    name: 'repo-animations-static-bridge',
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        if (!req.url) return next();
        const cleanUrl = req.url.split('?')[0];
        const prefix = '/repo-animations/';
        if (!cleanUrl.startsWith(prefix)) return next();

        const subPath = decodeURIComponent(cleanUrl.slice(prefix.length));
        if (subPath === 'manifest.json') {
          const files = scanAnimations();
          res.setHeader('Content-Type', 'application/json; charset=utf-8');
          res.end(
            JSON.stringify(
              { directory: 'animations', files: files.map((f) => `animations/${f}`) },
              null,
              2,
            ),
          );
          return;
        }

        const resolved = path.resolve(animationDir, subPath);
        if (
          !resolved.startsWith(animationDir + path.sep) ||
          !fs.existsSync(resolved) ||
          !fs.statSync(resolved).isFile()
        ) {
          res.statusCode = 404;
          res.end('Not found');
          return;
        }
        res.setHeader('Content-Type', 'application/octet-stream');
        fs.createReadStream(resolved).pipe(res);
      });
    },
    writeBundle(outputOptions) {
      const outDir = outputOptions.dir
        ? path.resolve(__dirname, outputOptions.dir)
        : path.resolve(__dirname, 'dist');
      const destRoot = path.join(outDir, 'repo-animations');
      fs.mkdirSync(destRoot, { recursive: true });
      const files = scanAnimations();
      fs.writeFileSync(
        path.join(destRoot, 'manifest.json'),
        `${JSON.stringify({ directory: 'animations', files: files.map((f) => `animations/${f}`) }, null, 2)}\n`,
        'utf-8',
      );
      for (const file of files) {
        const src = path.join(animationDir, file);
        if (fs.existsSync(src)) fs.copyFileSync(src, path.join(destRoot, file));
      }
    },
  };
}

